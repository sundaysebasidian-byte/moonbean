#!/usr/bin/env python3
"""Generate Unicode 16 case data from CPython's public string API, not oracle source.

Run with the pinned oracle venv Python, then moon fmt. No Beancount imports.
Case_Ignorable is observed through Python's contextual final-sigma behavior.
"""
from pathlib import Path
import json
import unicodedata


def ranges(points):
    result=[]
    for p in points:
        if result and p==result[-1][1]+1:result[-1][1]=p
        else:result.append([p,p])
    return result


def generate():
    if unicodedata.unidata_version!='16.0.0':
        raise SystemExit('requires Python with Unicode 16.0.0')
    upper=[];lower=[];cased=[];ignorable=[]
    for n in range(0x110000):
        c=chr(n)
        if c.upper()!=c:upper.append((n,c.upper()))
        if c.lower()!=c:lower.append((n,c.lower()))
        if c.islower() or c.isupper() or c.istitle():cased.append(n)
        if ('A'+c+'Σ').lower().endswith('ς') and not ('.'+c+'Σ').lower().endswith('ς'):
            ignorable.append(n)
    lines=['// Generated by scripts/generate_unicode_case.py from CPython Unicode 16.0.0.',
           '// No Beancount/beanquery implementation or data is used.','']
    for name,values in [('upper',upper),('lower',lower)]:
        lines+=['///|',f'fn unicode_{name}_piece(c : Char) -> String? {{','  match c.to_int() {']
        lines += [f'    {n} => Some({json.dumps(v,ensure_ascii=False)})' for n,v in values]
        lines += ['    _ => None','  }','}','']
    for name,values in [('cased',cased),('ignorable',ignorable)]:
        lines+=['///|',f'let unicode_{name}_ranges : Array[(Int32, Int32)] = [']
        lines += [f'  ({a}, {b}),' for a,b in ranges(values)]
        lines += [']','']
    Path('query/unicode_data.mbt').write_text('\n'.join(lines))
    print(f'upper mappings: {len(upper)}, lower mappings: {len(lower)}')

if __name__=='__main__': generate()

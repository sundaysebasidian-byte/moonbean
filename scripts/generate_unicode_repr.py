#!/usr/bin/env python3
"""Generate printable ranges from CPython's public Unicode 16 string API."""
from pathlib import Path
import unicodedata
assert unicodedata.unidata_version=='16.0.0'
ranges=[]
for n in range(0x110000):
 if chr(n).isprintable():
  if ranges and n==ranges[-1][1]+1:ranges[-1][1]=n
  else:ranges.append([n,n])
Path('query/unicode_repr_data.mbt').write_text('// Generated by scripts/generate_unicode_repr.py; CPython Unicode 16.0.0.\n\n///|\nlet unicode_printable_ranges : Array[(Int32, Int32)] = [\n'+''.join(f'  ({a}, {b}),\n' for a,b in ranges)+']\n')

#!/usr/bin/env python3
"""Generate account character masks from the pinned public account predicate.

Run with /tmp/moonbean-r4-oracle/bin/python, then moon fmt.
No implementation source or internal regex is accessed.
"""
from importlib.metadata import version
from pathlib import Path
from beancount.core.account import is_valid

assert version('beancount') == '3.2.3'
ranges = []
start = last = None
mask = 0
for value in range(128, 0x110000):
    if 0xD800 <= value <= 0xDFFF:
        current = 0
    else:
        char = chr(value)
        root = is_valid(char + ':A')
        child = is_valid('Assets:' + char)
        body = is_valid('Assets:A' + char)
        current = int(root) | (2 if child and not root else 0) | (4 if body else 0)
    if current == mask and current and value == last + 1:
        last = value
    else:
        if mask:
            ranges.append((start, last, mask))
        start = last = value
        mask = current
if mask:
    ranges.append((start, last, mask))
p = Path('ast/account_unicode.mbt')
p.write_text('// Public Beancount 3.2.3 account predicate masks. Generated by scripts/generate_account_unicode.py.\n///|\nlet account_unicode_ranges : Array[(Int32, Int32, Int32)] = [\n' + ''.join(f'  ({a}, {b}, {m}),\n' for a, b, m in ranges) + ']\n')
print(len(ranges), 'account character ranges')

#!/usr/bin/env python3
"""Generate account character ranges from the pinned public Unicode database."""
from pathlib import Path
import unicodedata
assert unicodedata.unidata_version == '16.0.0'
ranges = []
start = last = None
mask = 0
for value in range(128, 0x110000):
    category = unicodedata.category(chr(value))
    current = (1 if category == 'Lu' else 0) | (2 if category == 'Nd' else 0) | (4 if category.startswith('L') or category == 'Nd' else 0)
    if current == mask and current and value == last + 1:
        last = value
    else:
        if mask: ranges.append((start, last, mask))
        start = last = value
        mask = current
if mask: ranges.append((start,last,mask))
p = Path('ast/account_unicode.mbt')
p.write_text('// Unicode 16.0 account character ranges. Generated by scripts/generate_account_unicode.py.\n///|\nlet account_unicode_ranges : Array[(Int, Int, Int)] = [\n' + ''.join(f'  ({a}, {b}, {m}),\n' for a,b,m in ranges) + ']\n')
print(len(ranges), 'Unicode ranges')

#!/usr/bin/env python3
"""Generate numeric character data through CPython's public Unicode API."""
from pathlib import Path
import unicodedata
assert unicodedata.unidata_version == '16.0.0'
starts=[n for n in range(0x110000) if chr(n).isdecimal() and unicodedata.decimal(chr(n))==0]
Path('query/unicode_numbers.mbt').write_text('// CPython Unicode 16.0 decimal digit blocks; generated by scripts/generate_unicode_numbers.py.\n///|\nlet unicode_decimal_starts : Array[Int32] = ['+', '.join(map(str,starts))+']\n')
